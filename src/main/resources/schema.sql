-- ====================================================================
-- Point of Sale (POS) and Inventory Management System - Database Schema
-- Compatible with Oracle Database 21c XE & Standard ANSI SQL
-- ====================================================================

-- 1. Roles Table
CREATE TABLE ROLES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(200)
);

-- 2. Users Table
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP
);

-- 3. User Roles Mapping Table
CREATE TABLE USER_ROLES (
    USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_UR_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID) ON DELETE CASCADE
);

-- 4. Token Blacklist Table (for logout revocation)
CREATE TABLE TOKEN_BLACKLIST (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TOKEN VARCHAR2(512) NOT NULL UNIQUE,
    EXPIRY_DATE TIMESTAMP NOT NULL,
    REVOKED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IDX_BLACKLIST_TOKEN ON TOKEN_BLACKLIST(TOKEN);

-- 5. Categories Table
CREATE TABLE CATEGORIES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255),
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 6. Products Table
CREATE TABLE PRODUCTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    SKU VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(500),
    PRICE NUMBER(12,2) NOT NULL,
    COST_PRICE NUMBER(12,2),
    STOCK_QUANTITY NUMBER(10) DEFAULT 0 NOT NULL,
    REORDER_THRESHOLD NUMBER(10) DEFAULT 10 NOT NULL,
    TAX_RATE NUMBER(5,2) DEFAULT 18.00 NOT NULL,
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CATEGORY_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT FK_PROD_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(ID)
);
CREATE UNIQUE INDEX IDX_PRODUCT_SKU ON PRODUCTS(SKU);
CREATE INDEX IDX_PRODUCT_CATEGORY ON PRODUCTS(CATEGORY_ID);
CREATE INDEX IDX_PRODUCT_ACTIVE ON PRODUCTS(ACTIVE);

-- 7. Stock Movements Audit Table
CREATE TABLE STOCK_MOVEMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER NOT NULL,
    MOVEMENT_TYPE VARCHAR2(30) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL,
    PREVIOUS_STOCK NUMBER(10) NOT NULL,
    NEW_STOCK NUMBER(10) NOT NULL,
    REASON VARCHAR2(255),
    REFERENCE_ID VARCHAR2(100),
    PERFORMED_BY NUMBER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_SM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID),
    CONSTRAINT FK_SM_USER FOREIGN KEY (PERFORMED_BY) REFERENCES USERS(ID)
);
CREATE INDEX IDX_SM_PRODUCT ON STOCK_MOVEMENTS(PRODUCT_ID);
CREATE INDEX IDX_SM_CREATED_AT ON STOCK_MOVEMENTS(CREATED_AT);

-- 8. Sales Transactions Table
CREATE TABLE SALES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    SALE_DATE TIMESTAMP NOT NULL,
    CUSTOMER_ID NUMBER,
    CASHIER_ID NUMBER NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,
    DISCOUNT_AMOUNT NUMBER(12,2) DEFAULT 0.00 NOT NULL,
    TAX_AMOUNT NUMBER(12,2) DEFAULT 0.00 NOT NULL,
    TOTAL_AMOUNT NUMBER(12,2) NOT NULL,
    PAYMENT_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    NOTES VARCHAR2(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT FK_SALE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_SALE_CASHIER FOREIGN KEY (CASHIER_ID) REFERENCES USERS(ID)
);
CREATE UNIQUE INDEX IDX_SALE_INVOICE ON SALES(INVOICE_NUMBER);
CREATE INDEX IDX_SALE_DATE ON SALES(SALE_DATE);
CREATE INDEX IDX_SALE_PAYMENT_STATUS ON SALES(PAYMENT_STATUS);

-- 9. Sale Items Table
CREATE TABLE SALE_ITEMS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SALE_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    PRODUCT_NAME VARCHAR2(150) NOT NULL,
    PRODUCT_SKU VARCHAR2(50) NOT NULL,
    UNIT_PRICE NUMBER(12,2) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,
    TAX_RATE NUMBER(5,2) NOT NULL,
    TAX_AMOUNT NUMBER(12,2) NOT NULL,
    TOTAL NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_SI_SALE FOREIGN KEY (SALE_ID) REFERENCES SALES(ID) ON DELETE CASCADE,
    CONSTRAINT FK_SI_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID)
);
CREATE INDEX IDX_ITEM_SALE ON SALE_ITEMS(SALE_ID);
CREATE INDEX IDX_ITEM_PRODUCT ON SALE_ITEMS(PRODUCT_ID);

-- 10. Payments Table
CREATE TABLE PAYMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SALE_ID NUMBER NOT NULL,
    PAYMENT_DATE TIMESTAMP NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    PAYMENT_MODE VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    TRANSACTION_REFERENCE VARCHAR2(100),
    GATEWAY_RESPONSE VARCHAR2(500),
    NOTES VARCHAR2(255),
    RECORDED_BY NUMBER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PAY_SALE FOREIGN KEY (SALE_ID) REFERENCES SALES(ID),
    CONSTRAINT FK_PAY_USER FOREIGN KEY (RECORDED_BY) REFERENCES USERS(ID)
);
CREATE INDEX IDX_PAYMENT_SALE ON PAYMENTS(SALE_ID);
CREATE INDEX IDX_PAYMENT_DATE ON PAYMENTS(PAYMENT_DATE);

-- 11. Cash Shifts Table
CREATE TABLE CASH_SHIFTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SHIFT_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    CASHIER_ID NUMBER NOT NULL,
    OPENED_AT TIMESTAMP NOT NULL,
    CLOSED_AT TIMESTAMP,
    OPENING_BALANCE NUMBER(12,2) NOT NULL,
    CLOSING_BALANCE NUMBER(12,2),
    EXPECTED_BALANCE NUMBER(12,2),
    DIFFERENCE NUMBER(12,2),
    STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    NOTES VARCHAR2(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CS_CASHIER FOREIGN KEY (CASHIER_ID) REFERENCES USERS(ID)
);
CREATE UNIQUE INDEX IDX_SHIFT_NUMBER ON CASH_SHIFTS(SHIFT_NUMBER);

-- 12. Cash Entries Table
CREATE TABLE CASH_ENTRIES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SHIFT_ID NUMBER NOT NULL,
    ENTRY_TYPE VARCHAR2(30) NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    REASON VARCHAR2(255),
    ENTRY_TIME TIMESTAMP NOT NULL,
    RECORDED_BY NUMBER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CE_SHIFT FOREIGN KEY (SHIFT_ID) REFERENCES CASH_SHIFTS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_CE_USER FOREIGN KEY (RECORDED_BY) REFERENCES USERS(ID)
);
CREATE INDEX IDX_ENTRY_SHIFT ON CASH_ENTRIES(SHIFT_ID);
CREATE INDEX IDX_ENTRY_TIME ON CASH_ENTRIES(ENTRY_TIME);
